// diagnosticSettingTypeSet is diagnosticSettingTypes by upper-case type.
var diagnosticSettingTypeSet = func() map[string]bool {
	set := make(map[string]bool, len(diagnosticSettingTypes))
	for _, typ := range diagnosticSettingTypes {
		set[strings.ToUpper(typ)] = true
	}
	return set
}()

// hasDiagnosticSettings reports whether resources of the Resource Manager
// type typ can have diagnostic settings (see diagnosticSettingTypes).
func hasDiagnosticSettings(typ string) bool {
	return diagnosticSettingTypeSet[strings.ToUpper(typ)]
}
