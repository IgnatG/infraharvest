// The query service refuses the types a provider's services list (see
// harvest.Profile.ListedTypes). AWS's services declare theirs, beside
// their listers, and TestListedTypesAreDeclared checks the declarations
// against the lister code. Each other provider's listed_types.go holds
// them as the services reference finds them in its code; it is rewritten
// with -update, like the reference:
//
//	go test ./internal/cli -run TestGoldenListedTypes -update

// listedTypesFile is the name of the generated file in a provider's
// package.
const listedTypesFile = "listed_types.go"

// declaredListedTypes are the providers whose services declare the types
// they list, rather than have them generated.
var declaredListedTypes = []string{"aws"}

// The types a provider's services declare are those their lister code
// names, with those the catalogue assigns them.
func TestListedTypesAreDeclared(t *testing.T) {
	for _, name := range declaredListedTypes {
		provider := providers.New(name)
		if provider == nil {
			t.Skipf("built without %s", name)
		}
		listed, err := listedTypes(provider)
		if err != nil {
			t.Fatal(err)
		}
		declared := provider.Profile().ListedTypes
		for _, typ := range slices.Sorted(maps.Keys(listed)) {
			if service, ok := declared[typ]; !ok {
				t.Errorf("%s: %s lists %s, which it doesn't declare", name, listed[typ], typ)
			} else if service != listed[typ] {
				t.Errorf("%s: %s is listed by %s first, but declared by %s", name, typ, listed[typ], service)
			}
		}
		for _, typ := range slices.Sorted(maps.Keys(declared)) {
			if _, ok := listed[typ]; !ok {
				t.Errorf("%s: %s declares %s, which its lister code doesn't name", name, declared[typ], typ)
			}
		}
	}
}

func TestGoldenListedTypes(t *testing.T) {
	for _, name := range referenceProviders {
		if slices.Contains(declaredListedTypes, name) {
			continue
		}
		provider := providers.New(name)
		if provider == nil {
			t.Skipf("built without %s", name)
		}
		listed, err := listedTypes(provider)
		if err != nil {
			t.Fatal(err)
		}
		source, err := parseProviderPackage(provider)
		if err != nil {
			t.Fatal(err)
		}
		pkg := source.importPath[strings.LastIndex(source.importPath, "/")+1:]
		got, err := renderListedTypes(pkg, listed)
		if err != nil {
			t.Fatal(err)
		}
		path := filepath.Join("..", "..", filepath.FromSlash(strings.TrimPrefix(source.importPath, modulePath)), listedTypesFile)
		if *update {
			if err := os.WriteFile(path, got, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(want, got) {
			t.Errorf("%s is out of date: run go test ./internal/cli -run TestGoldenListedTypes -update, or the remote workflow's golden task with packages ./internal/cli", path)
		}
		// The provider reads what was generated.
		if !reflect.DeepEqual(provider.Profile().ListedTypes, listed) {
			t.Errorf("%s: its profile's ListedTypes isn't the generated listedTypes", name)
		}
	}
}

// listedTypes returns the types provider's services list, as the services
// reference finds them in its code and catalogue, each with the first service by name that lists it.
func listedTypes(provider harvest.Provider) (map[string]string, error) {
	cat, err := catalogue.Builtin(provider.Name())
	if err != nil {
		return nil, err
	}
	source, err := parseProviderPackage(provider)
	if err != nil {
		return nil, err
	}
	profile := provider.Profile()
	optIn := profile.OptInServices
	supported := provider.Services()
	listed := map[string]string{}
	for _, service := range slices.Sorted(slices.Values(slices.Concat(importer.Services(provider), optIn))) {
		if service == harvest.QueryService {
			continue
		}
		for _, typ := range serviceTypes(service, supported[service], source, cat, provider.Name(), slices.Contains(optIn, service), profile.MissingTypes) {
			if _, ok := listed[typ]; !ok {
				listed[typ] = service
			}
		}
	}
	return listed, nil
}

// renderListedTypes writes listed as the Go file of package pkg.
func renderListedTypes(pkg string, listed map[string]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Copyright 2026 Gabriel Ignat\n// SPDX-License-Identifier: AGPL-3.0-only\n\n")
	b.WriteString("// Code generated by TestGoldenListedTypes in internal/cli/listedtypes_test.go. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("// listedTypes are the resource types the provider's services list, with\n// the service that lists each (see harvest.Profile.ListedTypes).\n")
	b.WriteString("var listedTypes = map[string]string{\n")
	for _, typ := range slices.Sorted(maps.Keys(listed)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", typ, listed[typ])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
